#!/usr/bin/env bash
# Installs FDM-TUI and creates the "tfdm" command to launch the application directly.
#
#   bash install.sh                 install (or update if already installed)
#   bash install.sh --all           + videos (yt-dlp) and torrents (libtorrent)
#   bash install.sh --video         + videos (yt-dlp)
#   bash install.sh --torrent       + torrents (libtorrent via pip)
#   bash install.sh --system-site-packages
#                                   venv sees system packages
#                                   (useful with python3-libtorrent installed via dnf/apt)
#   bash install.sh --uninstall     uninstall (configuration is kept)
#
# Optional variables: TFDM_HOME (installation directory), TFDM_BIN (command directory)
set -euo pipefail

NAME="tfdm"
SRC="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
INSTALL_DIR="${TFDM_HOME:-$HOME/.local/share/tfdm}"
BIN_DIR="${TFDM_BIN:-$HOME/.local/bin}"
LAUNCHER="$BIN_DIR/$NAME"
MARKER="$INSTALL_DIR/.tfdm-install"
EXTRAS=()
VENV_ARGS=()
UNINSTALL=0

error() { echo "Error: $*" >&2; exit 1; }
info()  { echo "→ $*"; }

usage() { sed -n '2,15p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
    case "$1" in
        --video)   EXTRAS+=(yt-dlp) ;;
        --torrent) EXTRAS+=(libtorrent) ;;
        --all)     EXTRAS+=(yt-dlp libtorrent) ;;
        --system-site-packages) VENV_ARGS+=(--system-site-packages) ;;
        --uninstall) UNINSTALL=1 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
    esac
    shift
done

# ---------------------------------------------------------------- uninstall
if [ "$UNINSTALL" -eq 1 ]; then
    [ -f "$LAUNCHER" ] && rm -f "$LAUNCHER" && info "Command removed: $LAUNCHER"
    if [ -f "$MARKER" ]; then
        rm -rf "$INSTALL_DIR"
        info "Directory removed: $INSTALL_DIR"
    else
        info "No installation found in $INSTALL_DIR"
    fi
    echo "Your configuration and download list are kept in ~/.config/fdm_tui"
    exit 0
fi

# ---------------------------------------------------------------- checks
[ -f "$SRC/fdm_tui.py" ] || error "fdm_tui.py not found next to install.sh (run the script from the project directory)"

PYTHON="$(command -v python3 || true)"
[ -n "$PYTHON" ] || error "python3 was not found. Install it first (sudo dnf install python3  /  sudo apt install python3)"
"$PYTHON" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' \
    || error "Python 3.10 or newer is required (current version: $("$PYTHON" -V 2>&1))"

# ---------------------------------------------------------------- installation
info "Installing to $INSTALL_DIR"
mkdir -p "$INSTALL_DIR" "$BIN_DIR"
touch "$MARKER"
rm -rf "$INSTALL_DIR/venv"

info "Creating virtual environment…"
if ! "$PYTHON" -m venv ${VENV_ARGS[@]+"${VENV_ARGS[@]}"} "$INSTALL_DIR/venv"; then
    error "failed to create venv. On Ubuntu/Debian: sudo apt install python3-venv"
fi

info "Installing dependencies…"
PIP="$INSTALL_DIR/venv/bin/pip"
"$PIP" install --quiet --upgrade pip
if [ -f "$SRC/requirements.txt" ]; then
    "$PIP" install --quiet -r "$SRC/requirements.txt"
else
    "$PIP" install --quiet textual httpx
fi
for extra in ${EXTRAS[@]+"${EXTRAS[@]}"}; do
    info "Installing $extra…"
    "$PIP" install --quiet "$extra" || echo "  (failed to install $extra: optional feature skipped)" >&2
done

install -m 0644 "$SRC/fdm_tui.py" "$INSTALL_DIR/fdm_tui.py"

# ---------------------------------------------------------------- tfdm command
cat > "$LAUNCHER" <<LAUNCHER_EOF
#!/usr/bin/env bash
# Generated by install.sh — launches FDM-TUI
exec "$INSTALL_DIR/venv/bin/python" "$INSTALL_DIR/fdm_tui.py" "\$@"
LAUNCHER_EOF
chmod +x "$LAUNCHER"
info "Command created: $LAUNCHER"

OTHER="$(command -v "$NAME" 2>/dev/null || true)"
if [ -n "$OTHER" ] && [ "$OTHER" != "$LAUNCHER" ]; then
    echo "Warning: another command \"$NAME\" already exists ($OTHER) and takes precedence over the new one." >&2
fi

# ---------------------------------------------------------------- PATH
NEW_TERMINAL=0
case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
        LINE="export PATH=\"$BIN_DIR:\$PATH\""
        DONE=0
        for rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
            [ -f "$rc" ] || continue
            grep -qF "$LINE" "$rc" || printf '\n# Added by tfdm installation\n%s\n' "$LINE" >> "$rc"
            DONE=1
        done
        if [ "$DONE" -eq 0 ]; then
            printf '# Added by tfdm installation\n%s\n' "$LINE" >> "$HOME/.bashrc"
        fi
        NEW_TERMINAL=1
        ;;
esac

echo
echo "✓ FDM-TUI is installed."
if [ "$NEW_TERMINAL" -eq 1 ]; then
    echo "  $BIN_DIR has just been added to your PATH: open a new terminal"
    echo "  (or run: source ~/.bashrc), then type:  $NAME"
    echo "  (if you use fish or another shell, add $BIN_DIR to your PATH yourself)"
else
    echo "  Just type:  $NAME"
fi
echo "  Examples:  $NAME   |   $NAME \"https://site/file.iso\"   |   $NAME -f links.txt"
echo "  Update: run  bash install.sh   —   Uninstall:  bash install.sh --uninstall"
